#!/usr/bin/env node
/**
 * Builds ../exam-rooms.js (the Compass "Exam Rooms" tool) from:
 *   src/part0_print_shared.js   print CSS, fitStyle, hidden-iframe printing
 *                                (shared with the Exam Seating Manager)
 *   exam-rooms/core.js          names, matching, seating
 *   exam-rooms/docs.js          documents and the plan file
 *   exam-rooms/ui.js            the panel and the Compass calls
 * Run:  node build_exam_rooms.js
 * Never hand-edit ../exam-rooms.js: it is overwritten on every build.
 */
const fs = require('fs');
const path = require('path');

const PARTS = ['src/part0_print_shared.js', 'exam-rooms/core.js', 'exam-rooms/docs.js', 'exam-rooms/ui.js'];
const OUT = path.join(__dirname, '..', 'exam-rooms.js');

const body = PARTS.map(f => '/* ---- ' + f + ' ---- */\n' + fs.readFileSync(path.join(__dirname, f), 'utf8')).join('\n');
const js = '/* Exam Rooms — GENERATED by exam-seating/build_exam_rooms.js. Do not edit; edit the parts and rebuild.\n' +
  '   Runs inside Compass with the teacher\'s own login and talks only to Compass. */\n' +
  '(function () {\n' + body + '\n' +
  // Hook for exam-rooms.test.py (and for checking in the browser console). It lives
  // only in this Compass tab's memory, like the rest of the tool's data.
  'if (!window.__examRooms) window.__examRooms = { ER: ER, model: erBuildModel, open: erOpenText,\n' +
  '  docs: function () { return erDocsFor(erBuildModel()); },\n' +
  '  plan: function () { return erPlanFile(ER.S, erBuildModel(), erSaveState()); },\n' +
  '  fn: { matchName: erMatchName, parseName: erParseCompassName, preferredFirst: erPreferredFirst, seat: erSeat,\n' +
  '        expandCodes: erExpandCodes, ranges: erGroupRanges, shortSession: erShortSession, splitWhole: erSplitWhole } };\n' +
  'erStart();\n})();\n';

// Pure ASCII output: every non-ASCII character becomes a \uXXXX escape, so the
// script works whatever character set the page loading it declares.
const ascii = js.replace(/[^\x00-\x7f]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
fs.writeFileSync(OUT, ascii);
console.log('Built ' + path.relative(process.cwd(), OUT) + ' (' + Math.round(js.length / 1024) + ' KB)');
